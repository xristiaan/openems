package io.openems.edge.simulator.replay.zone;

import org.osgi.service.metatype.annotations.AttributeDefinition;
import org.osgi.service.metatype.annotations.ObjectClassDefinition;

@ObjectClassDefinition(//
		name = "Simulator Comfort Zone", //
		description = "A simulated room with its own heating / cooling device (an air conditioner): the device's thermostat "
				+ "regulates to the set point it is sent, the room warms and cools with the outdoor temperature. "
				+ "Thermometer (room temperature), Hvac (on/off, heat/cool, set point) and meter (electrical power) in one.")
@interface Config {

	@AttributeDefinition(name = "Component-ID", description = "Unique ID of this Component")
	String id() default "zone0";

	@AttributeDefinition(name = "Alias", description = "Human-readable name of this Component; defaults to Component-ID")
	String alias() default "";

	@AttributeDefinition(name = "Is enabled?", description = "Is this Component enabled?")
	boolean enabled() default true;

	@AttributeDefinition(name = "Outdoor thermometer-ID", description = "The outdoor temperature (e.g. the replayed outdoor0).")
	String outdoor_id() default "outdoor0";

	@AttributeDefinition(name = "Fallback outdoor temperature [°C]", description = "While the outdoor thermometer has no value.")
	double fallbackOutdoorTemperature() default 10.0;

	@AttributeDefinition(name = "Initial room temperature [°C]")
	double initialTemperature() default 19.0;

	@AttributeDefinition(name = "Thermal Capacity [kWh/°C]")
	double thermalCapacityKwhPerK() default 1.8;

	@AttributeDefinition(name = "TransmissionFactor [W/°C]")
	double transmissionWPerK() default 50.0;

	@AttributeDefinition(name = "Maximum power [W]", description = "The device's maximum electrical power.")
	int maxPowerW() default 2000;

	@AttributeDefinition(name = "COP", description = "Heating, constant.")
	double cop() default 3.5;

	@AttributeDefinition(name = "EER", description = "Cooling, constant.")
	double eer() default 3.5;

	@AttributeDefinition(name = "Thermostat band [°C]", description = "Below the set point by this much the device runs at full power, at the set point not at all (proportional in between).")
	double thermostatBand() default 0.5;

	@AttributeDefinition(name = "Outdoor thermometer target filter", description = "This is auto-generated by 'Outdoor thermometer-ID'.")
	String outdoor_target() default "(enabled=true)";

	String webconsole_configurationFactory_nameHint() default "Simulator Comfort Zone [{id}]";
}
