package io.openems.edge.controller.pv;

import org.osgi.service.metatype.annotations.AttributeDefinition;
import org.osgi.service.metatype.annotations.ObjectClassDefinition;

@ObjectClassDefinition(//
		name = "Controller PV", //
		description = "Plan-able Controller for a PV inverter — a producer in the DP Controller's arbitration "
				+ "(negative budget, bounded by the forecast), planned against Modes Off/On/Boost/Forced and "
				+ "executed as an active-power limit (curtailment).")
@interface Config {

	@AttributeDefinition(name = "Component-ID", description = "Unique ID of this Component")
	String id() default "ctrlPv0";

	@AttributeDefinition(name = "Alias", description = "Human-readable name of this Component; defaults to Component-ID")
	String alias() default "";

	@AttributeDefinition(name = "Is enabled?", description = "Is this Component enabled?")
	boolean enabled() default true;

	@AttributeDefinition(name = "PV-Inverter-ID", description = "ID of the ManagedSymmetricPvInverter to plan and curtail.")
	String pvInverter_id();

	@AttributeDefinition(name = "Inverter rated power", description = "inverterRatedkW: the inverter's AC rated output, in W.")
	int inverterRatedW() default 1_000;

	@AttributeDefinition(name = "Min controllable power", description = "P_frac_min: lowest controllable output, as a fraction of the rated power (0-1). OFF curtails to this. Use 0 if the inverter can curtail to zero.")
	double pFracMin() default 0.05;

	@AttributeDefinition(name = "Max controllable power", description = "P_frac_max: highest controllable output, as a fraction of the rated power (0-1).")
	double pFracMax() default 1.0;

	@AttributeDefinition(name = "Curtailment supported?", description = "Whether the inverter accepts an active-power limit at all. If not, this Controller still plans the forecast production but never sends a limit.")
	boolean curtailmentSupported() default true;

	@AttributeDefinition(name = "Forecast channel", description = "The Channel whose prediction (from the PredictorManager) is this PV's production forecast, as Component-ID/Channel-ID.")
	String forecastChannel() default "_sum/ProductionActivePower";

	@AttributeDefinition(name = "Deadband", description = "Deadband_P: changes of the limit smaller than this are not sent, in W.")
	int deadbandW() default 100;

	@AttributeDefinition(name = "Min curtailment period", description = "MinCurtailmentPeriod_s: minimum time between two changes of the limit, from any source, in seconds.")
	int minCurtailmentPeriodSeconds() default 15;

	@AttributeDefinition(name = "Ramp limit", description = "RampLimit: maximum change rate of the limit, in W per second.")
	int rampLimitWPerSecond() default 1_000;

	@AttributeDefinition(name = "PV-Inverter target filter", description = "This is auto-generated by 'PV-Inverter-ID'.")
	String pvInverter_target() default "(enabled=true)";

	String webconsole_configurationFactory_nameHint() default "Controller PV [{id}]";

}
