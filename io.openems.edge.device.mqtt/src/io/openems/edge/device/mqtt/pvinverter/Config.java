package io.openems.edge.device.mqtt.pvinverter;

import org.osgi.service.metatype.annotations.AttributeDefinition;
import org.osgi.service.metatype.annotations.ObjectClassDefinition;

@ObjectClassDefinition(//
		name = "PV-Inverter MQTT", //
		description = "A PV inverter behind a platform bridge (Homey, Home Assistant): its power arrives on an MQTT state topic, its ActivePowerLimit is sent as a set-power command.")
@interface Config {

	@AttributeDefinition(name = "Component-ID", description = "Unique ID of this Component")
	String id() default "pv0";

	@AttributeDefinition(name = "Alias", description = "Human-readable name of this Component; defaults to Component-ID")
	String alias() default "";

	@AttributeDefinition(name = "Is enabled?", description = "Is this Component enabled?")
	boolean enabled() default true;

	@AttributeDefinition(name = "Device-ID", description = "The device ID on the platform bridge (the deviceId of its commands and state topic).")
	String deviceId();

	@AttributeDefinition(name = "Rated power", description = "The inverter rated power in W; commands also carry the limit as a fraction of it.")
	int ratedPowerW() default 4_000;

	@AttributeDefinition(name = "State topic", description = "Topic with the device readings as JSON; {deviceId} is replaced.")
	String stateTopic() default "energypro/homey/device/{deviceId}/state";

	@AttributeDefinition(name = "Power field", description = "JSON field in the state message holding the power in W.")
	String powerField() default "measure_power";

	@AttributeDefinition(name = "Invert power", description = "Flip the sign of the power reading, if the platform reports production as negative.")
	boolean powerInverted() default false;

	@AttributeDefinition(name = "Command topic", description = "Topic the set-power commands are published to.")
	String commandTopic() default "energypro/homey/command";

	@AttributeDefinition(name = "Ack topic", description = "Topic the platform acknowledges commands on.")
	String ackTopic() default "energypro/homey/command/ack";

	@AttributeDefinition(name = "Command deadband", description = "Smallest change of the limit worth sending, in W.")
	int deadbandW() default 50;

	@AttributeDefinition(name = "Minimum command interval", description = "Shortest time between two commands, in seconds.")
	int minCommandIntervalSeconds() default 5;

	@AttributeDefinition(name = "Resend interval", description = "An unchanged limit is sent again after this many seconds.")
	int resendIntervalSeconds() default 300;

	@AttributeDefinition(name = "Ack timeout", description = "Seconds after which a command without ack is reported as unacknowledged.")
	int ackTimeoutSeconds() default 30;

	@AttributeDefinition(name = "Stale after", description = "Seconds without a state message after which the readings count as stale (fault).")
	int staleAfterSeconds() default 120;

	@AttributeDefinition(name = "Mqtt-ID", description = "ID of the BridgeMqtt Component.")
	String mqtt_id() default "mqtt0";

	@AttributeDefinition(name = "Mqtt target filter", description = "This is auto-generated by 'Mqtt-ID'.")
	String mqtt_target() default "(enabled=true)";

	String webconsole_configurationFactory_nameHint() default "PV-Inverter MQTT [{id}]";
}
