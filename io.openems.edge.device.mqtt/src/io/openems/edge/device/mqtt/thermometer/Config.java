package io.openems.edge.device.mqtt.thermometer;

import org.osgi.service.metatype.annotations.AttributeDefinition;
import org.osgi.service.metatype.annotations.ObjectClassDefinition;

@ObjectClassDefinition(//
		name = "Thermometer MQTT", //
		description = "A temperature from an MQTT state topic: a platform zone's (room's) temperature (Homey: energypro/homey/zone/{deviceId}/state), a sensor or any device with a temperature field.")
@interface Config {

	@AttributeDefinition(name = "Component-ID", description = "Unique ID of this Component")
	String id() default "thermometer0";

	@AttributeDefinition(name = "Alias", description = "Human-readable name of this Component; defaults to Component-ID")
	String alias() default "";

	@AttributeDefinition(name = "Is enabled?", description = "Is this Component enabled?")
	boolean enabled() default true;

	@AttributeDefinition(name = "Device-ID", description = "The ID that replaces {deviceId} in the state topic: the platform's zone ID (Homey zone) or the bridge's device ID.")
	String deviceId();

	@AttributeDefinition(name = "State topic", description = "Topic with the readings as JSON; {deviceId} is replaced. A device: energypro/homey/device/{deviceId}/state.")
	String stateTopic() default "energypro/homey/zone/{deviceId}/state";

	@AttributeDefinition(name = "Temperature field", description = "JSON field holding the temperature, in °C.")
	String temperatureField() default "measure_temperature";

	@AttributeDefinition(name = "Stale after", description = "Seconds without a state message after which the temperature counts as unknown (fault).")
	int staleAfterSeconds() default 120;

	@AttributeDefinition(name = "Mqtt-ID", description = "ID of the BridgeMqtt Component.")
	String mqtt_id() default "mqtt0";

	@AttributeDefinition(name = "Mqtt target filter", description = "This is auto-generated by 'Mqtt-ID'.")
	String mqtt_target() default "(enabled=true)";

	String webconsole_configurationFactory_nameHint() default "Thermometer MQTT [{id}]";
}
