package io.openems.edge.device.mqtt.hvac;

import org.osgi.service.metatype.annotations.AttributeDefinition;
import org.osgi.service.metatype.annotations.ObjectClassDefinition;

import io.openems.common.types.MeterType;

@ObjectClassDefinition(//
		name = "HVAC MQTT", //
		description = "A heating / cooling device (air conditioner, heat pump zone) behind a platform bridge (Homey, Home Assistant): its state, room temperature and power arrive on an MQTT state topic; what a Controller writes to on/off, mode and set point is sent as commands, if enabled.")
@interface Config {

	@AttributeDefinition(name = "Component-ID", description = "Unique ID of this Component")
	String id() default "hvac0";

	@AttributeDefinition(name = "Alias", description = "Human-readable name of this Component; defaults to Component-ID")
	String alias() default "";

	@AttributeDefinition(name = "Is enabled?", description = "Is this Component enabled?")
	boolean enabled() default true;

	@AttributeDefinition(name = "Device-ID", description = "The device ID on the platform bridge (the deviceId of its state topic).")
	String deviceId();

	@AttributeDefinition(name = "Meter type", description = "CONSUMPTION_METERED if a grid meter already measures the device, else CONSUMPTION_NOT_METERED.")
	MeterType type() default MeterType.CONSUMPTION_METERED;

	@AttributeDefinition(name = "State topic", description = "Topic with the device readings as JSON; {deviceId} is replaced.")
	String stateTopic() default "energypro/homey/device/{deviceId}/state";

	@AttributeDefinition(name = "Power field", description = "JSON field holding the electrical power, in W. Empty: no power (e.g. when a separate meter measures the device).")
	String powerField() default "measure_power";

	@AttributeDefinition(name = "Energy field", description = "JSON field holding the device's own energy counter, in kWh (e.g. MELCloud's meter_power, updated hourly). Empty: the energy is calculated from the power.")
	String energyField() default "meter_power";

	@AttributeDefinition(name = "Room temperature field", description = "JSON field holding the room temperature, in °C.")
	String temperatureField() default "measure_temperature";

	@AttributeDefinition(name = "On/off field", description = "JSON field holding on (true) or off (false).")
	String onField() default "onoff";

	@AttributeDefinition(name = "Mode field", description = "JSON field holding the mode as text: 'heat', 'cool' or 'off' (other values, e.g. auto, dry, fan, are reported as undefined; 'off' also means switched off).")
	String modeField() default "thermostat_mode";

	@AttributeDefinition(name = "Set point field", description = "JSON field holding the set point, in °C.")
	String setpointField() default "target_temperature";

	@AttributeDefinition(name = "Send commands", description = "Send what a Controller writes (on/off, mode, set point) to the device. Off: read-only.")
	boolean commandsEnabled() default false;

	@AttributeDefinition(name = "Command topic", description = "Topic the commands are published to.")
	String commandTopic() default "energypro/homey/command";

	@AttributeDefinition(name = "Ack topic", description = "Topic the platform acknowledges commands on.")
	String ackTopic() default "energypro/homey/command/ack";

	@AttributeDefinition(name = "Set point step", description = "The device's set point step in °C (MELCloud: 0.5); set points are rounded to it.")
	double setpointStep() default 0.5;

	@AttributeDefinition(name = "Minimum command interval", description = "Shortest time between two commands of the same kind, in seconds.")
	int minCommandIntervalSeconds() default 10;

	@AttributeDefinition(name = "Ack timeout", description = "Seconds after which a command without ack (or a failed one) is sent again.")
	int ackTimeoutSeconds() default 60;

	@AttributeDefinition(name = "Stale after", description = "Seconds without a state message after which the readings count as stale (fault).")
	int staleAfterSeconds() default 120;

	@AttributeDefinition(name = "Mqtt-ID", description = "ID of the BridgeMqtt Component.")
	String mqtt_id() default "mqtt0";

	@AttributeDefinition(name = "Mqtt target filter", description = "This is auto-generated by 'Mqtt-ID'.")
	String mqtt_target() default "(enabled=true)";

	String webconsole_configurationFactory_nameHint() default "HVAC MQTT [{id}]";
}
