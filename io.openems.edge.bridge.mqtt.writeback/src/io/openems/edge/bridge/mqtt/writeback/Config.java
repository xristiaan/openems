package io.openems.edge.bridge.mqtt.writeback;

import org.osgi.service.metatype.annotations.AttributeDefinition;
import org.osgi.service.metatype.annotations.ObjectClassDefinition;

@ObjectClassDefinition(//
		name = "Bridge Mqtt Writeback", //
		description = "Subscribes to one MQTT topic and writes each incoming payload into one target "
				+ "Channel — the inbound counterpart to Controller.Api.Mqtt's outbound auto-publish, "
				+ "needed for any resource whose measured state lives only on an external platform "
				+ "(e.g. a Homey-reported room temperature) rather than a native OpenEMS Component. "
				+ "One instance per (topic, target Channel) mapping.")
@interface Config {

	@AttributeDefinition(name = "Component-ID", description = "Unique ID of this Component")
	String id() default "mqttWriteback0";

	@AttributeDefinition(name = "Alias", description = "Human-readable name of this Component; defaults to Component-ID")
	String alias() default "";

	@AttributeDefinition(name = "Is enabled?", description = "Is this Component enabled?")
	boolean enabled() default true;

	@AttributeDefinition(name = "MQTT Topic", description = "The topic to subscribe to; may include MQTT wildcards (+, #) only if every match should write the same target Channel.")
	String topic();

	@AttributeDefinition(name = "Target Channel", description = "The Channel to write each incoming payload into, as ComponentId/ChannelId (e.g. ctrlComfortZone0/MeasuredTemperature).")
	String targetChannel();

	@AttributeDefinition(name = "Mqtt-ID", description = "ID of the BridgeMqtt Component to subscribe through.")
	String mqtt_id() default "mqtt0";

	@AttributeDefinition(name = "Mqtt target filter", description = "This is auto-generated by 'Mqtt-ID'.")
	String Mqtt_target() default "(enabled=true)";

	String webconsole_configurationFactory_nameHint() default "Bridge Mqtt Writeback [{id}]";

}
