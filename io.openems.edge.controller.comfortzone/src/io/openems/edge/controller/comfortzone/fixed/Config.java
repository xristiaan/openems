package io.openems.edge.controller.comfortzone.fixed;

import org.osgi.service.metatype.annotations.AttributeDefinition;
import org.osgi.service.metatype.annotations.ObjectClassDefinition;

import io.openems.edge.hvac.api.HvacMode;

@ObjectClassDefinition(//
		name = "Controller HVAC Fixed", //
		description = "Holds a heating / cooling device at a fixed on/off, mode and set point: for a manual test, or as a fallback. Not together with a Comfort Zone Controller on the same device.")
@interface Config {

	@AttributeDefinition(name = "Component-ID", description = "Unique ID of this Component")
	String id() default "ctrlHvacFixed0";

	@AttributeDefinition(name = "Alias", description = "Human-readable name of this Component; defaults to Component-ID")
	String alias() default "";

	@AttributeDefinition(name = "Is enabled?", description = "Is this Component enabled?")
	boolean enabled() default true;

	@AttributeDefinition(name = "HVAC-ID", description = "ID of the heating / cooling device (Hvac).")
	String hvac_id() default "hvac0";

	@AttributeDefinition(name = "On", description = "Switch the device on (true) or off (false).")
	boolean on() default true;

	@AttributeDefinition(name = "Mode", description = "HEAT or COOL.")
	HvacMode mode() default HvacMode.HEAT;

	@AttributeDefinition(name = "Set point", description = "The set point, in °C.")
	double setpoint() default 20.0;

	@AttributeDefinition(name = "HVAC target filter", description = "This is auto-generated by 'HVAC-ID'.")
	String hvac_target() default "(enabled=true)";

	String webconsole_configurationFactory_nameHint() default "Controller HVAC Fixed [{id}]";
}
