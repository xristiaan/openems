package io.openems.edge.controller.ess.battery;

import org.osgi.service.metatype.annotations.AttributeDefinition;
import org.osgi.service.metatype.annotations.ObjectClassDefinition;

@ObjectClassDefinition(//
		name = "Controller Ess Battery", //
		description = "Plan-able Controller for a battery energy storage system — day-ahead DP planning "
				+ "against Modes Off/On/Boost/Forced/Forced-Boost, each with its own SoC band and C-rate.")
@interface Config {

	@AttributeDefinition(name = "Component-ID", description = "Unique ID of this Component")
	String id() default "ctrlEssBattery0";

	@AttributeDefinition(name = "Alias", description = "Human-readable name of this Component; defaults to Component-ID")
	String alias() default "";

	@AttributeDefinition(name = "Is enabled?", description = "Is this Component enabled?")
	boolean enabled() default true;

	@AttributeDefinition(name = "Ess-ID", description = "ID of the ManagedSymmetricEss to plan.")
	String ess_id();

	@AttributeDefinition(name = "SoC Min Normal", description = "Lower bound of the NORMAL SoC band (fraction, 0-1), used by On/Forced.")
	double socMinNormal() default 0.20;

	@AttributeDefinition(name = "SoC Max Normal", description = "Upper bound of the NORMAL SoC band (fraction, 0-1), used by On/Forced.")
	double socMaxNormal() default 0.80;

	@AttributeDefinition(name = "SoC Min Safe", description = "Lower bound of the physically-safe SoC band (fraction, 0-1), used by Boost/Forced-Boost.")
	double socMinSafe() default 0.10;

	@AttributeDefinition(name = "SoC Max Safe", description = "Upper bound of the physically-safe SoC band (fraction, 0-1), used by Boost/Forced-Boost.")
	double socMaxSafe() default 0.90;

	@AttributeDefinition(name = "On C-rate, Charge", description = "ON mode's charge C-rate (1/h).")
	double cRateOnCharge() default 0.25;

	@AttributeDefinition(name = "On C-rate, Discharge", description = "ON mode's discharge C-rate (1/h).")
	double cRateOnDischarge() default 0.25;

	@AttributeDefinition(name = "Boost C-rate, Charge", description = "BOOST mode's charge C-rate (1/h).")
	double cRateBoostCharge() default 0.5;

	@AttributeDefinition(name = "Boost C-rate, Discharge", description = "BOOST mode's discharge C-rate (1/h).")
	double cRateBoostDischarge() default 0.5;

	@AttributeDefinition(name = "Forced C-rate, Charge", description = "FORCED mode's charge C-rate (1/h).")
	double cRateForcedCharge() default 0.25;

	@AttributeDefinition(name = "Forced C-rate, Discharge", description = "FORCED mode's discharge C-rate (1/h).")
	double cRateForcedDischarge() default 0.5;

	@AttributeDefinition(name = "Forced Boost C-rate, Charge", description = "FORCED_BOOST mode's charge C-rate (1/h).")
	double cRateForcedBoostCharge() default 0.5;

	@AttributeDefinition(name = "Forced Boost C-rate, Discharge", description = "FORCED_BOOST mode's discharge C-rate (1/h).")
	double cRateForcedBoostDischarge() default 1.0;

	@AttributeDefinition(name = "Charge efficiency", description = "Round-trip charge efficiency (0-1).")
	double chargeEfficiency() default 0.95;

	@AttributeDefinition(name = "Discharge efficiency", description = "Round-trip discharge efficiency (0-1).")
	double dischargeEfficiency() default 0.95;

	@AttributeDefinition(name = "Degradation cost", description = "c_deg: cost of battery degradation from cycling, in Euro per kWh of throughput.")
	double degradationCostEurPerKwh() default 0.10;

	@AttributeDefinition(name = "Degradation cost, boost multiplier", description = "c_deg_boost: multiplier applied to the degradation cost when the operating C-rate is at or above 0.5C.")
	double degradationCostBoostMultiplier() default 2.0;

	@AttributeDefinition(name = "Deviation cost", description = "comfort_cost: cost of 1 kWh of deviation from the target per slot, in Euro per kWh.")
	double deviationCostEurPerKwh() default 0.05;

	@AttributeDefinition(name = "Deadline missed cost", description = "Cost of 1 kWh of deviation from the target AT a deadline slot, in Euro per kWh. Not yet given a considered default upstream — review before relying on it.")
	double deadlineMissedCostEurPerKwh() default 1.0;

	@AttributeDefinition(name = "Ess target filter", description = "This is auto-generated by 'Ess-ID'.")
	String ess_target() default "(enabled=true)";

	String webconsole_configurationFactory_nameHint() default "Controller Ess Battery [{id}]";

}
